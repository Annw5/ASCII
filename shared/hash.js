// Хеш: из трёх чисел делает «случайное», но всегда одинаковое число
export function hash(a, b, c) {                          // принимает три числа
  let n = Math.imul(a, 374761393) + Math.imul(b, 668265263) + Math.imul(c, 1274126177);   // перемешиваем числа умножением (imul — умножение целых без переполнения)
  n = Math.imul(n ^ (n >>> 13), 1274126177);             // ещё раз перемешиваем: сдвиг, исключающее ИЛИ, умножение
  return (n ^ (n >>> 16)) >>> 0;                         // последнее перемешивание; >>> 0 делает число неотрицательным
}                                                        // конец функции
